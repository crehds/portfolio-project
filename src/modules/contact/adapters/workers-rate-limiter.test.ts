import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { everythingAbout, rejectionOf, spyOnConsole } from './testing';
import {
  createWorkersRateLimiter,
  type RateLimitBinding,
} from './workers-rate-limiter';

// Every test drives a fake binding. Nothing here reaches Cloudflare.

const KEY = '203.0.113.7';

/** What a failing binding could quote back: its key or something of its own. */
const LEAKY_TEXT = 'key=203.0.113.7 internal=BINDING-DETAIL-SENTINEL';

let consoleSpies: ReturnType<typeof spyOnConsole>;

beforeEach(() => {
  consoleSpies = spyOnConsole();
});

afterEach(() => {
  vi.restoreAllMocks();
});

/** A binding that answers `{ success }` for every key. */
function bindingAnswering(success: boolean) {
  return {
    limit: vi.fn<RateLimitBinding['limit']>(async () => ({ success })),
  };
}

describe('the structural binding type', () => {
  // Checked by `astro check`: the `RateLimit` binding type generated by `wrangler types`
  // must keep fitting what the adapter asks of a binding.
  it('is fitted by the real Workers RateLimit binding type', () => {
    const fits = (real: RateLimit): RateLimitBinding => real;

    expect(fits).toBeTypeOf('function');
  });
});

describe('createWorkersRateLimiter: mapping the binding to the port', () => {
  it('resolves true when the binding says success: true', async () => {
    const limiter = createWorkersRateLimiter(bindingAnswering(true));

    await expect(limiter(KEY)).resolves.toBe(true);
  });

  it('resolves false when the binding says success: false', async () => {
    const limiter = createWorkersRateLimiter(bindingAnswering(false));

    await expect(limiter(KEY)).resolves.toBe(false);
  });

  it('counts the request under exactly the key it was given', async () => {
    const binding = bindingAnswering(true);

    await createWorkersRateLimiter(binding)(KEY);

    expect(binding.limit).toHaveBeenCalledTimes(1);
    expect(binding.limit).toHaveBeenCalledWith({ key: KEY });
    expect(Object.keys(binding.limit.mock.calls[0][0])).toEqual(['key']);
  });

  it.each(['unknown', '2001:db8::1', 'a'.repeat(200)])(
    'passes the key %j through untouched',
    async (key) => {
      const binding = bindingAnswering(true);

      await createWorkersRateLimiter(binding)(key);

      expect(binding.limit).toHaveBeenCalledWith({ key });
    },
  );

  it('answers each key from its own call', async () => {
    const limit = vi
      .fn<RateLimitBinding['limit']>()
      .mockResolvedValueOnce({ success: true })
      .mockResolvedValueOnce({ success: false })
      .mockResolvedValueOnce({ success: true });
    const limiter = createWorkersRateLimiter({ limit });

    expect(await limiter('a')).toBe(true);
    expect(await limiter('b')).toBe(false);
    expect(await limiter('c')).toBe(true);
    expect(limit.mock.calls.map(([{ key }]) => key)).toEqual(['a', 'b', 'c']);
  });

  // A runtime method called without its receiver fails with an "Illegal invocation" error,
  // and a real binding is one: so `limit` must be called on the binding itself.
  it('calls limit on the binding, so a method that needs its receiver works', async () => {
    const receivers: unknown[] = [];
    const binding: RateLimitBinding = {
      async limit() {
        receivers.push(this);
        return { success: true };
      },
    };

    await createWorkersRateLimiter(binding)(KEY);

    expect(receivers).toEqual([binding]);
  });

  it('logs nothing when the binding answers', async () => {
    await createWorkersRateLimiter(bindingAnswering(true))(KEY);
    await createWorkersRateLimiter(bindingAnswering(false))(KEY);

    for (const spy of consoleSpies) {
      expect(spy).not.toHaveBeenCalled();
    }
  });
});

// A binding that cannot answer is the caller's call to make: `submitContact` lets the
// request through (fail open) and logs one fixed line. So the adapter rejects, with fixed
// text, and logs nothing itself: a line here too would report one failure twice.
describe('createWorkersRateLimiter: a binding that cannot answer', () => {
  const failures: [string, () => RateLimitBinding][] = [
    [
      'rejects',
      () => ({
        limit: async () => {
          throw new Error(LEAKY_TEXT, { cause: new Error(LEAKY_TEXT) });
        },
      }),
    ],
    [
      'throws before it returns a promise',
      () => ({
        limit: () => {
          throw new Error(LEAKY_TEXT);
        },
      }),
    ],
    [
      'rejects with something that is not an Error',
      () => ({
        limit: () => Promise.reject(LEAKY_TEXT),
      }),
    ],
  ];

  it.each(failures)(
    'rejects with a fixed message when it %s',
    async (_label, make) => {
      const error = await rejectionOf(createWorkersRateLimiter(make())(KEY));

      expect(error.message).toBe('The rate limit binding failed');
    },
  );

  it.each(failures)(
    'keeps what the binding said out of the error when it %s',
    async (_label, make) => {
      const error = await rejectionOf(createWorkersRateLimiter(make())(KEY));

      const exposed = everythingAbout(error);
      expect(exposed).not.toContain('BINDING-DETAIL-SENTINEL');
      expect(exposed).not.toContain(KEY);
      expect(error.constructor).toBe(Error);
      expect(error.cause).toBeUndefined();
      expect('cause' in error).toBe(false);
    },
  );

  it.each(failures)('logs nothing when it %s', async (_label, make) => {
    await rejectionOf(createWorkersRateLimiter(make())(KEY));

    for (const spy of consoleSpies) {
      expect(spy).not.toHaveBeenCalled();
    }
  });

  it('asks the binding once and does not retry', async () => {
    const limit = vi.fn<RateLimitBinding['limit']>(async () => {
      throw new Error('unavailable');
    });

    await rejectionOf(createWorkersRateLimiter({ limit })(KEY));

    expect(limit).toHaveBeenCalledTimes(1);
  });

  // Neither `true` nor `false` is the binding's answer here, and guessing either would
  // hide it: a denial would block a visitor, an allowance would go unnoticed. Rejecting
  // gets it logged once and the request through.
  it.each([
    [undefined],
    [null],
    [{}],
    [{ success: 'true' }],
    [{ success: 1 }],
    [{ success: null }],
    [{ allowed: true }],
    ['ok'],
    [true],
  ])(
    'rejects when the binding answers %j instead of { success }',
    async (answer) => {
      const binding = {
        limit: async () => answer,
      } as unknown as RateLimitBinding;

      const error = await rejectionOf(createWorkersRateLimiter(binding)(KEY));

      expect(error.message).toBe(
        'The rate limit binding answered with an unexpected result',
      );
      expect(error.cause).toBeUndefined();
    },
  );
});
